interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (code: LanguageCode) => void;
  currentLanguage: LanguageOption;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>("tr");

  useEffect(() => {
    try {
      const saved = (localStorage.getItem("heycoderz_language") ||
        localStorage.getItem("heycoderz_site_lang")) as LanguageCode;
      if (saved && DICTIONARY[saved]) {
        setLanguageState(saved);
      }
    } catch {}
  }, []);

  const setLanguage = (code: LanguageCode) => {
    setLanguageState(code);
    try {
      localStorage.setItem("heycoderz_language", code);
      localStorage.setItem("heycoderz_site_lang", code);
      // Dispatch custom event for real-time subscribers
      if (typeof window !== "undefined") {
        window.dispatchEvent(new CustomEvent("heycoderz-lang-change", { detail: code }));
      }
    } catch {}
  };

  const currentLanguage = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    const langDict = DICTIONARY[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to Turkish
    if (DICTIONARY.tr && DICTIONARY.tr[key]) {
      return DICTIONARY.tr[key];
    }
    // Fallback to English
    if (DICTIONARY.en && DICTIONARY.en[key]) {
      return DICTIONARY.en[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, currentLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
